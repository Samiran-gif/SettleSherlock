@dataclass(slots=True)
class DetectedPattern:
    """A behavioural pattern found by a deterministic detector."""

    pattern_id: str
    name: str
    description: str
    severity: Severity
    confidence: float
    transaction_ids: list[str] = field(default_factory=list)
    entities: list[str] = field(default_factory=list)
    metrics: dict[str, Any] = field(default_factory=dict)
    grade: EvidenceGrade = EvidenceGrade.STRONG_EVIDENCE
    provenance: Provenance = Provenance.DETERMINISTIC

    def to_dict(self) -> dict[str, Any]:
        return {
            "pattern_id": self.pattern_id,
            "name": self.name,
            "description": self.description,
            "severity": self.severity.value,
            "confidence": round(self.confidence, 3),
            "transaction_ids": list(self.transaction_ids),
            "entities": list(self.entities),
            "metrics": _plain(self.metrics),
            "grade": self.grade.value,
            "provenance": self.provenance.value,
        }


@dataclass(slots=True)
class EvidenceItem:
    """Links one finding back to the record that supports it."""

    transaction_id: str | None
    finding: str
    importance: Importance
    pattern_id: str | None = None
    grade: EvidenceGrade = EvidenceGrade.STRONG_EVIDENCE
    provenance: Provenance = Provenance.DETERMINISTIC

    def to_dict(self) -> dict[str, Any]:
        return {
            "transaction_id": self.transaction_id,
            "finding": self.finding,
            "importance": self.importance.value,
            "pattern_id": self.pattern_id,
            "grade": self.grade.value,
            "provenance": self.provenance.value,
        }


@dataclass(slots=True)
class TimelineEvent:
    """One entry in the reconstructed chronology."""

    timestamp: datetime | None
    event: str
    importance: Importance
    transaction_id: str | None = None
    details: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "timestamp": self.timestamp.isoformat() if self.timestamp else None,
            "transaction_id": self.transaction_id,
            "event": self.event,
            "importance": self.importance.value,
            "details": _plain(self.details),
        }


@dataclass(slots=True)
class Entity:
    """An account, user, bank, gateway or merchant touched by the case."""

    entity_id: str
    entity_type: str
    roles: list[str] = field(default_factory=list)
    transaction_count: int = 0
    outbound_count: int = 0
    inbound_count: int = 0
    total_amount: Decimal | None = None
    currencies: list[str] = field(default_factory=list)
    linked_entities: list[str] = field(default_factory=list)
    flags: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {
            "entity_id": self.entity_id,
            "entity_type": self.entity_type,
            "roles": sorted(self.roles),
            "transaction_count": self.transaction_count,
            "outbound_count": self.outbound_count,
            "inbound_count": self.inbound_count,
            "total_amount": _plain(self.total_amount),
            "currencies": sorted(self.currencies),
            "linked_entities": sorted(self.linked_entities),
            "flags": sorted(set(self.flags)),
        }


@dataclass(slots=True)
class Hypothesis:
    """A candidate explanation for the observed evidence."""

    conclusion: str
    confidence: float
    reasoning: list[str] = field(default_factory=list)
    supporting_pattern_ids: list[str] = field(default_factory=list)
    supporting_transaction_ids: list[str] = field(default_factory=list)
    contradicting_observations: list[str] = field(default_factory=list)
    grade: EvidenceGrade = EvidenceGrade.HYPOTHESIS
    provenance: Provenance = Provenance.DETERMINISTIC

    def to_dict(self) -> dict[str, Any]:
        return {
            "conclusion": self.conclusion,
            "confidence": round(self.confidence, 3),
            "reasoning": list(self.reasoning),
            "supporting_pattern_ids": list(self.supporting_pattern_ids),
            "supporting_transaction_ids": list(self.supporting_transaction_ids),
            "contradicting_observations": list(self.contradicting_observations),
            "grade": self.grade.value,
            "provenance": self.provenance.value,
        }


@dataclass(slots=True)
class InvestigationReport:
    """The complete structured output of an investigation."""

    case_summary: str
    severity: Severity
    suspicious_transactions: list[dict[str, Any]] = field(default_factory=list)
    entities_involved: list[Entity] = field(default_factory=list)
    timeline: list[TimelineEvent] = field(default_factory=list)
    detected_patterns: list[DetectedPattern] = field(default_factory=list)
    root_cause: Hypothesis | None = None
    evidence: list[EvidenceItem] = field(default_factory=list)
    alternative_hypotheses: list[Hypothesis] = field(default_factory=list)
    unknowns: list[str] = field(default_factory=list)
    recommended_next_steps: list[str] = field(default_factory=list)
    confirmed_facts: list[str] = field(default_factory=list)
    statistics: dict[str, Any] = field(default_factory=dict)
    data_quality: DataQuality | None = None
    case_summary_source: Provenance = Provenance.DETERMINISTIC
    ai_narrative: dict[str, Any] | None = None
    meta: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        """Render the report as the JSON contract consumed by the backend."""
        return {
            "case_summary": self.case_summary,
            "case_summary_source": self.case_summary_source.value,
            "severity": self.severity.value,
            "suspicious_transactions": _plain(self.suspicious_transactions),
            "entities_involved": [e.to_dict() for e in self.entities_involved],
            "timeline": [t.to_dict() for t in self.timeline],
            "detected_patterns": [p.to_dict() for p in self.detected_patterns],
            "root_cause": self.root_cause.to_dict() if self.root_cause else None,
            "evidence": [e.to_dict() for e in self.evidence],
            "alternative_hypotheses": [h.to_dict() for h in self.alternative_hypotheses],
            "unknowns": list(self.unknowns),
            "recommended_next_steps": list(self.recommended_next_steps),
            "confirmed_facts": list(self.confirmed_facts),
            "statistics": _plain(self.statistics),
            "data_quality": self.data_quality.to_dict() if self.data_quality else None,
            "ai_narrative": _plain(self.ai_narrative),
            "meta": _plain(self.meta),
        }

    def to_json(self, indent: int | None = 2) -> str:
        """Serialize the report to a JSON string."""
        return json.dumps(self.to_dict(), indent=indent, sort_keys=False)

    # -- small helpers used by callers / tests ---------------------------- #
    def pattern_ids(self) -> list[str]:
        return [p.pattern_id for p in self.detected_patterns]

    def has_pattern(self, pattern_id: str) -> bool:
        return any(p.pattern_id == pattern_id for p in self.detected_patterns)

    def suspicious_transaction_ids(self) -> list[str]:
        return [str(t.get("transaction_id")) for t in self.suspicious_transactions]


def as_report_list(items: Sequence[Any]) -> list[dict[str, Any]]:
    """Convert a sequence of domain objects into plain dicts (test helper)."""
    return [_plain(i) for i in items]
