# Input side
# --------------------------------------------------------------------------- #
@dataclass(slots=True)
class ValidationIssue:
    """A single problem found while ingesting a raw evidence record."""

    record_index: int
    field: str
    problem: str
    severity: Severity = Severity.LOW
    transaction_id: str | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "record_index": self.record_index,
            "field": self.field,
            "problem": self.problem,
            "severity": self.severity.value,
            "transaction_id": self.transaction_id,
        }


@dataclass(slots=True)
class Transaction:
    """A normalized transaction record.

    Every field except ``index``/``transaction_id`` is optional: real-world
    evidence arrives incomplete and the agent must degrade gracefully rather
    than reject the case.
    """

    index: int
    transaction_id: str
    timestamp: datetime | None = None
    sender: str | None = None
    receiver: str | None = None
    amount: Decimal | None = None
    currency: str | None = None
    transaction_type: str | None = None
    account_id: str | None = None
    bank: str | None = None
    gateway: str | None = None
    status: TransactionStatus = TransactionStatus.UNKNOWN
    raw_status: str | None = None
    reference_id: str | None = None
    metadata: dict[str, Any] = field(default_factory=dict)
    raw: dict[str, Any] = field(default_factory=dict)
    issues: list[ValidationIssue] = field(default_factory=list)
    synthetic_id: bool = False

    # -- convenience accessors ------------------------------------------- #
    @property
    def counterparty_key(self) -> tuple[str, str]:
        """A stable ``(sender, receiver)`` key, tolerant of missing values."""
        return (self.sender or "<unknown-sender>", self.receiver or "<unknown-receiver>")

    @property
    def is_terminal_failure(self) -> bool:
        return self.status in (TransactionStatus.FAILED, TransactionStatus.CANCELLED)

    @property
    def is_value_moving(self) -> bool:
        """True when the record represents money that actually moved."""
        return self.status in (TransactionStatus.SUCCESS, TransactionStatus.PENDING)

    def to_dict(self) -> dict[str, Any]:
        return {
            "transaction_id": self.transaction_id,
            "timestamp": self.timestamp.isoformat() if self.timestamp else None,
            "sender": self.sender,
            "receiver": self.receiver,
            "amount": _plain(self.amount),
            "currency": self.currency,
            "transaction_type": self.transaction_type,
            "account_id": self.account_id,
            "bank": self.bank,
            "gateway": self.gateway,
            "status": self.status.value,
            "reference_id": self.reference_id,
            "metadata": _plain(self.metadata),
        }


@dataclass(slots=True)
class DataQuality:
    """Summary of how trustworthy the submitted evidence is."""

    records_submitted: int
    records_parsed: int
    records_rejected: int
    field_completeness: float
    missing_fields: dict[str, int] = field(default_factory=dict)
    issues: list[ValidationIssue] = field(default_factory=list)
    conflicting_record_count: int = 0

    @property
    def rejection_ratio(self) -> float:
        if self.records_submitted == 0:
            return 0.0
        return self.records_rejected / self.records_submitted

    def to_dict(self) -> dict[str, Any]:
        return {
            "records_submitted": self.records_submitted,
            "records_parsed": self.records_parsed,
            "records_rejected": self.records_rejected,
            "field_completeness": round(self.field_completeness, 3),
            "conflicting_record_count": self.conflicting_record_count,
            "missing_fields": dict(sorted(self.missing_fields.items())),
            "issues": [i.to_dict() for i in self.issues],
        }


